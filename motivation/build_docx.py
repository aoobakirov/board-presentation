def shade(cell,hexcolor):
    tcPr=cell._tc.get_or_add_tcPr(); sh=OxmlElement('w:shd')
    sh.set(qn('w:val'),'clear'); sh.set(qn('w:fill'),hexcolor); tcPr.append(sh)

def h(text,level,color=NAVY,size=None):
    p=doc.add_heading('',level=level); r=p.add_run(text)
    r.font.color.rgb=color; r.font.name='Calibri'
    if size: r.font.size=Pt(size)
    return p

def para(runs,after=6,size=11,align=None,italic=False,before=0):
    p=doc.add_paragraph()
    if align: p.alignment=align
    p.paragraph_format.space_after=Pt(after); p.paragraph_format.space_before=Pt(before)
    if isinstance(runs,str): runs=[(runs,False,INK)]
    for t,b,c in runs:
        r=p.add_run(t); r.bold=b; r.font.color.rgb=c; r.font.size=Pt(size); r.italic=italic
    return p

def bullet(text_runs,size=11):
    p=doc.add_paragraph(style='List Bullet'); p.paragraph_format.space_after=Pt(3)
    if isinstance(text_runs,str): text_runs=[(text_runs,False,INK)]
    for t,b,c in text_runs:
        r=p.add_run(t); r.bold=b; r.font.color.rgb=c; r.font.size=Pt(size)
    return p

def num(text,size=11):
    p=doc.add_paragraph(style='List Number'); p.paragraph_format.space_after=Pt(3)
    if isinstance(text,str): text=[(text,False,INK)]
    for t,b,c in text:
        r=p.add_run(t); r.bold=b; r.font.color.rgb=c; r.font.size=Pt(size)
    return p

def table(headers,rows,widths=None,fs_h=10,fs_c=9.5,hdr_color='13294B',zebra=('F1F5F9','FFFFFF')):
    t=doc.add_table(rows=1,cols=len(headers)); t.style='Table Grid'
    hdr=t.rows[0].cells
    for i,htext in enumerate(headers):
        shade(hdr[i],hdr_color); p=hdr[i].paragraphs[0]; r=p.add_run(htext)
        r.bold=True; r.font.color.rgb=RGBColor(0xFF,0xFF,0xFF); r.font.size=Pt(fs_h)
    for ri,row in enumerate(rows):
        cells=t.add_row().cells
        for i,val in enumerate(row):
            if i>=len(cells): continue
            shade(cells[i], zebra[0] if ri%2==0 else zebra[1])
            p=cells[i].paragraphs[0]
            if isinstance(val,tuple):
                txt,bold=val
            else:
                txt,bold=val,False
            r=p.add_run(txt); r.font.size=Pt(fs_c); r.font.color.rgb=INK; r.bold=bold
    if widths:
        for i,w in enumerate(widths):
            for row in t.rows: row.cells[i].width=Cm(w)
    doc.add_paragraph().paragraph_format.space_after=Pt(2)
    return t

